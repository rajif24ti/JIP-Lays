CREATE SCHEMA IF NOT EXISTS mobile;

-- 1. Tabel Users
CREATE TABLE IF NOT EXISTS mobile.users (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    email TEXT UNIQUE NOT NULL,
    nama TEXT,
    handphone TEXT,
    role TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. Tabel Karyawan
CREATE TABLE IF NOT EXISTS mobile.karyawan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama TEXT NOT NULL,
    divisi TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 3. Tabel Produksi
CREATE TABLE IF NOT EXISTS mobile.produksi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sekolah TEXT NOT NULL,
    menu TEXT NOT NULL,
    porsi TEXT NOT NULL,
    status TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 4. Enable Row Level Security (RLS)
ALTER TABLE mobile.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE mobile.karyawan ENABLE ROW LEVEL SECURITY;
ALTER TABLE mobile.produksi ENABLE ROW LEVEL SECURITY;

-- 5. Kebijakan Permisi RLS (Row Level Security)
CREATE POLICY "Allow read mobile.users" ON mobile.users FOR SELECT USING (true);
CREATE POLICY "Allow insert mobile.users" ON mobile.users FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow update mobile.users" ON mobile.users FOR UPDATE USING (true);

CREATE POLICY "Allow read mobile.karyawan" ON mobile.karyawan FOR SELECT USING (true);
CREATE POLICY "Allow insert mobile.karyawan" ON mobile.karyawan FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow update mobile.karyawan" ON mobile.karyawan FOR UPDATE USING (true);
CREATE POLICY "Allow delete mobile.karyawan" ON mobile.karyawan FOR DELETE USING (true);

CREATE POLICY "Allow read mobile.produksi" ON mobile.produksi FOR SELECT USING (true);
CREATE POLICY "Allow insert mobile.produksi" ON mobile.produksi FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow update mobile.produksi" ON mobile.produksi FOR UPDATE USING (true);
CREATE POLICY "Allow delete mobile.produksi" ON mobile.produksi FOR DELETE USING (true);

-- 6. Trigger Otomatis Pembuat Profil ke mobile.users saat Auth Signup
CREATE OR REPLACE FUNCTION mobile.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO mobile.users (id, email, nama, handphone, role)
    VALUES (
        NEW.id,
        NEW.email,
        COALESCE(NEW.raw_user_meta_data->>'nama', ''),
        COALESCE(NEW.raw_user_meta_data->>'handphone', ''),
        COALESCE(NEW.raw_user_meta_data->>'role', 'Penanggung Jawab Dapur')
    )
    ON CONFLICT (id) DO UPDATE SET
        email = EXCLUDED.email,
        nama = EXCLUDED.nama,
        handphone = EXCLUDED.handphone,
        role = EXCLUDED.role;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION mobile.handle_new_user();
